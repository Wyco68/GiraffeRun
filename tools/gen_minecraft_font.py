def default_glyph(ch):
    g = GLYPHS.get(ch.upper() if ch.isalpha() else ch)
    if g:
        return g
    if ch.islower() and ch.upper() in GLYPHS:
        return GLYPHS[ch.upper()]
    return GLYPHS["?"]


CHARS = []
for c in range(32, 127):
    CHARS.append(chr(c))

cell_w, cell_h = 8, 12
pad = 1
W, H = 512, 256
img = Image.new("RGBA", (W, H), (0, 0, 0, 0))
draw = ImageDraw.Draw(img)
cols = 16
char_lines = []
for i, ch in enumerate(CHARS):
    col, row = i % cols, i // cols
    x, y = col * (cell_w + pad), row * (cell_h + pad)
    pattern = default_glyph(ch)
    for row_i, line in enumerate(pattern):
        for col_i, bit in enumerate(line):
            if bit == "1":
                px, py = x + 1 + col_i, y + 2 + row_i
                draw.rectangle([px, py, px, py], fill=(255, 255, 255, 255))
    char_lines.append(
        f"char id={ord(ch)} x={x} y={y} width={cell_w} height={cell_h} "
        f"xoffset=0 yoffset=0 xadvance={cell_w + 1} page=0 chnl=15"
    )

lines = [
    'info face="Minecraft" size=12 bold=0 italic=0 charset="" unicode=1 stretchH=100 smooth=0 aa=1 padding=1,1,1,1 spacing=1,1',
    f"common lineHeight={cell_h} base=10 scaleW={W} scaleH={H} pages=1 packed=0 alphaChnl=1 redChnl=0 greenChnl=0 blueChnl=0",
    'page id=0 file="minecraft.png"',
    f"chars count={len(CHARS)}",
]
lines.extend(char_lines)
lines.append("kernings count=0")
out_dir = os.path.join(os.path.dirname(__file__), "..", "assets", "fonts")
os.makedirs(out_dir, exist_ok=True)
img.save(os.path.join(out_dir, "minecraft.png"))
with open(os.path.join(out_dir, "minecraft.fnt"), "w", encoding="utf-8") as f:
    f.write("\n".join(lines))
print("ok", len(CHARS), "glyphs ->", out_dir)
